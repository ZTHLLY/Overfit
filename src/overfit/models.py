@dataclass(frozen=True, slots=True)
class Page:
    """One page of a source document, as produced by the Parser (layer 2).

    The page number is captured here and nowhere else. If it is lost at this
    point no downstream layer can reconstruct it, and citations die with it.

    The two line collections carry something different from the text: what
    the *backend* knew about it. A layout-aware reader classifies every block
    it finds -- this is a running footer, that is a table, this is a formula
    -- and dropping those verdicts at the door means the cleaning stage has
    to rediscover them by guesswork, badly. A footer identified by a model
    reading the page is not the same kind of fact as a line that happened to
    appear on 65% of pages.

    Both are empty when the backend cannot say, which is the honest state for
    a reader that only returns glyphs. Cleaning falls back to statistics
    there, and only there.
    """

    number: int  # 1-based, matching what a human sees in a PDF reader
    text: str
    # Lines the backend identified as a running header or footer.
    furniture: tuple[str, ...] = ()
    # Lines belonging to a block that is not prose -- a table, an equation, a
    # heading, a caption. They look exactly like extraction debris (short,
    # unpunctuated, no bullet) and must never be deleted as such.
    structured: tuple[str, ...] = ()
    provenance: dict | None = None

    def __post_init__(self):
        object.__setattr__(
            self, "provenance", validate_provenance(self.provenance, text=self.text)
        )


@dataclass(frozen=True, slots=True)
class ParsedDocument:
    """A single source file after text extraction (layer 2 output)."""

    # Course-root-relative POSIX path, e.g. ``week03/lecture.pdf``.
    source: str
    pages: list[Page]
    provenance: dict | None = None

    def __post_init__(self):
        value = validate_provenance(self.provenance)
        if value and any(b["text_span"] is not None for b in value["blocks"]):
            raise ValueError("Document provenance has no container text coordinates")
        object.__setattr__(self, "provenance", value)

    @property
    def is_empty(self) -> bool:
        """True when extraction produced essentially nothing.

        Usually means the PDF is a scan with no text layer. The Parser should
        treat this as a hard failure rather than letting an empty document
        flow silently into the index.
        """
        return not any(page.text.strip() for page in self.pages)


@dataclass(frozen=True, slots=True)
class Chunk:
    """A retrievable unit of text (layer 3 output).

    Provenance is flattened onto every chunk on purpose: the chunk travels
    alone through embedding, storage and retrieval, so anything it does not
    carry itself is unrecoverable by the time an answer is written.
    """

    id: str  # deterministic, e.g. "lecture3_p12_c2" -- see make_id()
    text: str
    source: str
    page: int  # first page this chunk draws from
    page_end: int | None = None  # last page, when the chunk runs across a break
    section: str | None = None
    provenance: dict | None = None

    def __post_init__(self):
        object.__setattr__(
            self, "provenance", validate_provenance(self.provenance, text=self.text)
        )

    @staticmethod
    def make_id(source: str, page: int, index: int) -> str:
        """Build a stable chunk id.

        Determinism matters: re-ingesting an unchanged file must produce the
        same ids so that writes stay idempotent and a partly failed ingest
        repairs the index instead of duplicating it.

        The whole relative path is used, not just the file name. Course
        folders are routinely organised by week, and `week1/notes.md` and
        `week2/notes.md` are different documents -- collapsing them to
        "notes" made the second silently overwrite the first, losing an
        entire file's worth of material without any error.
        """
        path = Path(source)
        stem = "_".join([*path.parent.parts, path.stem]).strip("_") or path.stem
        return f"{stem}_p{page}_c{index}"

    @property
    def source_context(self) -> list[dict]:
        """Selected structural labels only; never original/audit block text.

        These travel separately from text so a slice through a long figure
        remains recognisable after its surrounding markers have been cut off.
        """
        value = validate_provenance(self.provenance, text=self.text)
        if value is None:
            return []
        return [
            {
                key: block[key]
                for key in (
                    "block_id",
                    "label",
                    "parent_id",
                    "context_id",
                    "text_span",
                    "mapping",
                )
            }
            for block in value["blocks"]
            if block["text_span"] is not None
            and block["text_span"][0] < block["text_span"][1]
        ]

    @property
    def citation(self) -> str:
        """How this chunk is referred to in a prompt and in the final answer.

        A page range appears only when the chunk genuinely spans one, so the
        common case stays short and readable.
        """
        if self.page_end and self.page_end != self.page:
            return f"{self.source} pp{self.page}-{self.page_end}"
        return f"{self.source} p{self.page}"


@dataclass(frozen=True, slots=True)
class EmbeddedChunk:
    """A chunk plus its vector (layer 4 output).

    Composition rather than inheritance, so that `chunk` stays a plain Chunk
    and can be handed to the store, the prompt builder and the renderer
    without any of them knowing an embedding was ever attached.
    """

    chunk: Chunk
    embedding: Vector

    @property
    def dim(self) -> int:
        return len(self.embedding)


