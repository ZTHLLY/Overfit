@dataclass(frozen=True, slots=True)
class RetrievedChunk:
    """A chunk returned by retrieval, preserving both ranking stages.

    Vector and reranker scores have unrelated scales.  Keeping them in
    separate fields is what makes rank movement auditable and prevents a
    second-stage score from erasing the dense-retrieval evidence.
    """

    chunk: Chunk
    vector_score: float
    vector_rank: int = 0
    rerank_score: float | None = None
    rerank_rank: int | None = None

    @property
    def score(self) -> float:
        """Read-only compatibility view used by older presentation code."""
        return self.rerank_score if self.rerank_score is not None else self.vector_score

    def with_score(self, score: float) -> RetrievedChunk:
        """Compatibility helper; preserve the dense score while reranking."""
        return replace(self, rerank_score=score)

    def with_rerank(self, score: float, rank: int) -> RetrievedChunk:
        return replace(self, rerank_score=score, rerank_rank=rank)


