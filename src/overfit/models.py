"""Data contracts shared by every layer of the pipeline.

This module is the spine of the project. It says nothing about *how* any
layer works -- only about the shape of the data that flows between them.
Implementations can be rewritten freely; these shapes should not change
without a deliberate decision.

Two families of types live here, and the split is intentional:

* **Frozen dataclasses** for internal pipeline data (Page, ParsedDocument,
  Chunk, EmbeddedChunk, RetrievedChunk). We construct these ourselves, so
  most fields need no boundary coercion. Optional versioned provenance is
  validated and copied because it also crosses storage/record boundaries.
  Frozen fields prevent reassignment; nested metadata is treated as read-only.

* **Pydantic models** for anything crossing a trust boundary -- namely the
  LLM's response (GeneratedItem, GeneratedExam). That data is generated by
  a model that may omit fields or invent shapes, so it must be validated,
  after the provider's `json_object` wire response is normalized locally.

Rule of thumb: pydantic at the boundary, dataclasses on the inside.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from overfit.provenance import validate_provenance

